#!/usr/bin/env python3
"""Run every M0 proposition through each available tactic independently."""

from __future__ import annotations

import argparse
import concurrent.futures
import json
import subprocess
import time
from dataclasses import asdict, dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reports" / "generated"
LEAN_SETUP = ROOT / ".lake" / "build" / "ir" / "Vermilion" / "Calibration" / "Obligations.setup.json"

CASES = [
    ("straightLine01", "straight-line", "examples/guide/requires_ensures.rs: octuple"),
    ("straightLine02", "straight-line", "examples/guide/requires_ensures.rs: call precondition"),
    ("straightLine03", "straight-line", "examples/guide/pervasive_example.rs: conditional minimum"),
    ("straightLine04", "straight-line", "examples/guide/references.rs: old/final state"),
    ("straightLine05", "straight-line", "examples/guide/getting_started.rs: assertion chain"),
    ("loop01", "loop", "examples/guide/loops.rs pattern: arithmetic invariant"),
    ("loop02", "loop", "examples/guide/pervasive_example.rs: counter invariant"),
    ("loop03", "loop", "examples/guide/pervasive_example.rs: bounded counter"),
    ("loop04", "loop", "examples/guide/loops.rs pattern: accumulator invariant"),
    ("recursion01", "recursion", "examples/guide/recursion.rs: decreases"),
    ("recursion02", "recursion", "examples/guide/recursion.rs: triangle step"),
    ("recursion03", "recursion", "examples/guide/recursion.rs: monotonic step"),
    ("quantifier01", "quantifier", "examples/guide/quants.rs: quantified implication"),
    ("quantifier02", "quantifier", "IronKV-style map update: same key"),
    ("quantifier03", "quantifier", "IronKV-style map update: distinct key"),
    ("quantifier04", "quantifier", "IronKV-style relation closure"),
    ("overflow01", "overflow", "examples/guide/requires_ensures.rs: i8 octuple bounds"),
    ("overflow02", "overflow", "examples/guide/overflow.rs: u8 addition"),
    ("collection01", "collection", "vstd Seq push/index shape"),
    ("collection02", "collection", "vstd Map insert/lookup shape"),
]

TACTICS = {
    "grind": "grind",
    "smt_cvc5_reconstruct": "smt (trust := false) [*]",
    "smt_cvc5_trust": "set_option warn.sorry false in smt (trust := true) [*]",
    "omega": "omega",
    "nlinarith": "nlinarith",
}

UNAVAILABLE = {
    "smt_z3_reconstruct": (
        "The pinned lean-smt tactic is hard-wired to cvc5; its generic Z3 "
        "process API is not connected to proof reconstruction."
    ),
    "smt_z3_trust": (
        "The pinned lean-smt tactic is hard-wired to cvc5; a trusted Z3 "
        "adapter would need a separate query/export path."
    ),
}


@dataclass(frozen=True)
class Result:
    case: str
    category: str
    source: str
    tactic: str
    status: str
    seconds: float
    diagnostic: str


def lean_source(case: str, tactic: str) -> str:
    name = f"Vermilion.Calibration.{case}"
    return (
        "import Vermilion.Calibration.Obligations\n\n"
        f"example : {name} := by\n"
        f"  unfold {name}\n"
        f"  {TACTICS[tactic]}\n"
    )


def run_one(case_data: tuple[str, str, str], tactic: str, timeout: int) -> Result:
    case, category, source = case_data
    case_dir = OUT / "cases"
    case_dir.mkdir(parents=True, exist_ok=True)
    path = case_dir / f"{case}__{tactic}.lean"
    path.write_text(lean_source(case, tactic), encoding="utf-8")
    started = time.perf_counter()
    try:
        proc = subprocess.run(
            ["lake", "env", "lean", str(path), "--setup", str(LEAN_SETUP)],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
        elapsed = time.perf_counter() - started
        output = "\n".join(part for part in (proc.stdout, proc.stderr) if part).strip()
        diagnostic = "" if proc.returncode == 0 else output[-1200:]
        status = "pass" if proc.returncode == 0 else "fail"
    except subprocess.TimeoutExpired as exc:
        elapsed = time.perf_counter() - started
        diagnostic = f"timeout after {timeout}s: {exc}"
        status = "timeout"
    return Result(case, category, source, tactic, status, elapsed, diagnostic)


def markdown(results: list[Result]) -> str:
    by_key = {(r.case, r.tactic): r for r in results}
    tactics = list(TACTICS) + list(UNAVAILABLE)
    lines = [
        "# Generated M0 calibration matrix",
        "",
        "Generated by `scripts/run_calibration.py`. Times are wall-clock Lean process times;",
        "they include per-process startup but exclude the one-time dependency build.",
        "",
        "| Obligation | Category | " + " | ".join(tactics) + " |",
        "|---|---|" + "---|" * len(tactics),
    ]
    for case, category, _ in CASES:
        cells = []
        for tactic in tactics:
            if tactic in UNAVAILABLE:
                cells.append("n/a")
            else:
                result = by_key[(case, tactic)]
                mark = "✓" if result.status == "pass" else "✗"
                cells.append(f"{mark} {result.seconds:.2f}s")
        lines.append(f"| `{case}` | {category} | " + " | ".join(cells) + " |")
    lines.extend(["", "## Solve rates", "", "| Tactic | Solved | Rate |", "|---|---:|---:|"])
    for tactic in TACTICS:
        solved = sum(r.status == "pass" for r in results if r.tactic == tactic)
        lines.append(f"| `{tactic}` | {solved}/20 | {solved / 20:.0%} |")
    for tactic, reason in UNAVAILABLE.items():
        lines.append(f"| `{tactic}` | n/a | n/a — {reason} |")
    union = sum(
        any(by_key[(case, tactic)].status == "pass" for tactic in TACTICS)
        for case, _, _ in CASES
    )
    lines.extend(["", f"Available-ladder union: **{union}/20 ({union / 20:.0%})**.", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--jobs", type=int, default=4)
    parser.add_argument("--timeout", type=int, default=30)
    parser.add_argument("--case", choices=[case for case, _, _ in CASES])
    parser.add_argument("--tactic", choices=list(TACTICS))
    args = parser.parse_args()

    selected_cases = [c for c in CASES if args.case is None or c[0] == args.case]
    selected_tactics = [t for t in TACTICS if args.tactic is None or t == args.tactic]
    jobs = [(case, tactic) for case in selected_cases for tactic in selected_tactics]
    OUT.mkdir(parents=True, exist_ok=True)
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = [pool.submit(run_one, case, tactic, args.timeout) for case, tactic in jobs]
        results = [future.result() for future in concurrent.futures.as_completed(futures)]
    results.sort(key=lambda r: ([c[0] for c in CASES].index(r.case), list(TACTICS).index(r.tactic)))

    (OUT / "M0-calibration.json").write_text(
        json.dumps(
            {
                "schema": 1,
                "lean_toolchain": "leanprover/lean4:v4.28.0",
                "unavailable": UNAVAILABLE,
                "results": [asdict(result) for result in results],
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    if len(selected_cases) == len(CASES) and len(selected_tactics) == len(TACTICS):
        (OUT / "M0-calibration.md").write_text(markdown(results), encoding="utf-8")

    failures = sum(result.status != "pass" for result in results)
    print(f"completed {len(results)} runs: {len(results) - failures} pass, {failures} fail/timeout")
    print(f"JSON: {OUT / 'M0-calibration.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
