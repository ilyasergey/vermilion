#!/usr/bin/env bash
# Merge literature/bib/*.bib into literature/bibliography.bib, de-duplicating by citekey.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=literature/bibliography.bib
{
  echo "% ============================================================================"
  echo "% Master bibliography for the Vermillion (Verus-in-Lean) planning project."
  echo "% GENERATED by scripts/merge-bib.sh from literature/bib/*.bib; edit fragments."
  echo "% ============================================================================"
  echo
  awk '
    /^[[:space:]]*@/ {
      key = $0
      sub(/^[[:space:]]*@[^{(]+[{(]/, "", key)
      sub(/,.*$/, "", key)
      gsub(/[[:space:]]/, "", key)
      if (key in seen) { skip = 1 } else { seen[key] = 1; skip = 0 }
    }
    { if (!skip) print }
  ' literature/bib/*.bib
} > "$OUT"

echo "Wrote $OUT"
grep -c '^[[:space:]]*@' "$OUT" | sed 's/^/Entries (after dedupe): /'
